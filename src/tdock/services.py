"""컨테이너 안에서 자동으로 띄우는 서비스(SSH, VS Code 터널, Jupyter, 직접 입력한 명령).

tdock으로 만든 컨테이너는 시작할 때 /etc/tdock/startup.sh 가 있으면 실행하는 훅을 가진다.
서비스 설정은 컨테이너 안 /etc/tdock 에 저장되므로 재시작과 commit 후 다시 만들기에도 유지된다.
"""

from __future__ import annotations

import io
import json
import re
import secrets
import shlex
import subprocess
import tarfile
import time

CONF_DIR = "/etc/tdock"
SCRIPT = f"{CONF_DIR}/startup.sh"
CONFIG = f"{CONF_DIR}/services.json"
KEYS = f"{CONF_DIR}/authorized_keys"
LOG_DIR = "/var/log/tdock"
HOOK_LABEL = "tdock.hook"

# 시작 훅: startup.sh 를 백그라운드로 실행한 뒤 원래 명령으로 넘어간다
HOOK = ('[ $# -gt 0 ] || set -- sleep infinity; '
        f'[ -x {SCRIPT} ] && {SCRIPT} boot </dev/null >/dev/null 2>&1 & exec "$@"')
HOOK_ARGV0 = "tdock"

# 기본 서비스: (id, 표시 이름, 확인할 실행 파일, 필요한 컨테이너 포트를 돌려주는 함수)
BUILTIN = [
    ("ssh", "SSH server", "sshd", lambda c: 22),
    ("tunnel", "VS Code tunnel", "code", lambda c: None),
    ("jupyter", "Jupyter Lab", "jupyter", lambda c: int(c.get("port") or 8888)),
]


def default_config() -> dict:
    return {
        "version": 1,
        "services": {
            "ssh": {"autostart": False, "keep": False, "authorized_keys": ""},
            "tunnel": {"autostart": False, "keep": False, "name": ""},
            "jupyter": {"autostart": False, "keep": False, "port": 8888, "token": secrets.token_hex(16)},
        },
        "custom": [],
    }


# ---------------------------------------------------------------- 훅이 있는 컨테이너의 원래 명령

def unwrap_hook(entrypoint: list | None, cmd: list | None) -> list | None:
    """훅으로 감싼 entrypoint/cmd 면 원래 명령을, 아니면 None."""
    cmd = cmd or []
    if (entrypoint or []) == ["/bin/sh"] and cmd[:3] == ["-c", HOOK, HOOK_ARGV0]:
        return cmd[3:]
    return None


def hook_args(argv: list[str]) -> tuple[list[str], list[str]]:
    """(이미지 앞에 붙일 옵션, 이미지 뒤에 붙일 인자)"""
    return (["--entrypoint", "/bin/sh", "--label", f"{HOOK_LABEL}=1"],
            ["-c", HOOK, HOOK_ARGV0, *argv])


# ---------------------------------------------------------------- startup.sh 생성

def _ids(cfg: dict) -> list[str]:
    return [s for s, *_ in BUILTIN] + [c["id"] for c in cfg.get("custom", [])]


def service_entry(cfg: dict, sid: str) -> dict:
    if sid in cfg["services"]:
        return cfg["services"][sid]
    return next(c for c in cfg["custom"] if c["id"] == sid)


def _body(cfg: dict, sid: str) -> str:
    s = service_entry(cfg, sid)
    q = shlex.quote
    if sid == "ssh":
        return ("mkdir -p /run/sshd\n"
                "    ls /etc/ssh/ssh_host_*_key >/dev/null 2>&1 || ssh-keygen -A\n"
                f"    chmod 600 {KEYS} 2>/dev/null\n"
                '    exec $SETSID "$(command -v sshd || echo /usr/sbin/sshd)" -D -e '
                "-o PermitRootLogin=prohibit-password -o PasswordAuthentication=no "
                f"-o AuthorizedKeysFile='.ssh/authorized_keys {KEYS}'")
    if sid == "tunnel":
        name = f" --name {q(s['name'])}" if s.get("name") else ""
        return f"exec $SETSID code tunnel --accept-server-license-terms{name}"
    if sid == "jupyter":
        return (f"exec $SETSID jupyter lab --ip=0.0.0.0 --port={int(s.get('port') or 8888)} --no-browser "
                f"--allow-root --ServerApp.token={q(s.get('token') or '')}")
    return f"exec $SETSID sh -c {q(s['command'])}"


def render_script(cfg: dict) -> str:
    ids = _ids(cfg)
    lines = [
        "#!/bin/sh",
        "# Generated by tdock (Services). Edit it from tdock rather than by hand.",
        f"LOG={LOG_DIR}; RUN=/run/tdock",
        'mkdir -p "$LOG" "$RUN"',
        "# 서비스마다 새 프로세스 그룹: 멈출 때 sh -c 아래의 자식까지 함께 끝낸다",
        'SETSID=$(command -v setsid || true)',
        f'SERVICES="{" ".join(ids)}"',
        "",
    ]
    for sid in ids:
        s = service_entry(cfg, sid)
        lines += [f"AUTO_{sid}={int(bool(s.get('autostart')))}; KEEP_{sid}={int(bool(s.get('keep')))}",
                  f"svc_{sid}() {{", f"    {_body(cfg, sid)}", "}", ""]
    lines += [r'''
# dash 의 kill 은 "--" 를 받지 않으므로 음수 PGID 를 바로 넘긴다
killgrp() { kill -TERM "-$1" 2>/dev/null || kill "$1" 2>/dev/null; }
sup_alive() { [ -f "$RUN/$1.sup" ] && kill -0 "$(cat "$RUN/$1.sup")" 2>/dev/null; }
svc_alive() { [ -f "$RUN/$1.pid" ] && kill -0 "$(cat "$RUN/$1.pid")" 2>/dev/null; }

start() {
    name=$1
    sup_alive "$name" && return 0
    eval keep=\$KEEP_$name
    log="$LOG/$name.log"
    # 로그가 너무 커지면 뒷부분만 남긴다
    [ -f "$log" ] && [ "$(wc -c <"$log")" -gt 5000000 ] && tail -c 1000000 "$log" >"$log.tmp" && mv "$log.tmp" "$log"
    (
        trap 'killgrp "$child"; exit 0' TERM INT
        while :; do
            echo "[$(date '+%F %T')] tdock: starting $name" >>"$log"
            svc_$name >>"$log" 2>&1 </dev/null &
            child=$!
            echo "$child" >"$RUN/$name.pid"
            wait "$child"; rc=$?
            echo "[$(date '+%F %T')] tdock: $name exited ($rc)" >>"$log"
            [ "$keep" = 1 ] || break
            sleep 3
        done
        rm -f "$RUN/$name.pid" "$RUN/$name.sup"
    ) </dev/null >/dev/null 2>&1 &
    echo $! >"$RUN/$name.sup"
}

stop() {
    name=$1
    sup_alive "$name" && kill "$(cat "$RUN/$name.sup")" 2>/dev/null
    svc_alive "$name" && killgrp "$(cat "$RUN/$name.pid")"
    rm -f "$RUN/$name.sup" "$RUN/$name.pid"
}

status() {
    # 설정에서 빠졌지만 아직 떠 있는 서비스도 보여준다 (awk/sed 없는 최소 이미지에서도 동작)
    names="$SERVICES"
    for f in "$RUN"/*.sup "$RUN"/*.pid; do
        [ -e "$f" ] || continue
        n=${f##*/}; n=${n%.*}
        case " $names " in *" $n "*) ;; *) names="$names $n" ;; esac
    done
    for name in $names; do
        if svc_alive "$name"; then echo "$name running"
        elif sup_alive "$name"; then echo "$name restarting"
        else echo "$name stopped"; fi
    done
}

case "$1" in
    boot)
        # 이전 실행의 PID 파일은 의미가 없다 (PID가 재사용될 수 있음)
        rm -f "$RUN"/*.sup "$RUN"/*.pid
        for name in $SERVICES; do eval a=\$AUTO_$name; [ "$a" = 1 ] && start "$name"; done ;;
    start) start "$2" ;;
    stop) stop "$2" ;;
    status) status ;;
    *) echo "usage: $0 boot|start NAME|stop NAME|status" >&2; exit 2 ;;
esac
'''.lstrip("\n")]
    return "\n".join(lines)


# ---------------------------------------------------------------- 컨테이너와 주고받기

def _docker(*args: str, data: bytes | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(["docker", *args], input=data, capture_output=True)


def read_config(container: str) -> dict | None:
    """컨테이너(멈춰 있어도 됨)에 저장된 서비스 설정. 없으면 None."""
    p = _docker("cp", f"{container}:{CONFIG}", "-")
    if p.returncode != 0:
        return None
    try:
        with tarfile.open(fileobj=io.BytesIO(p.stdout)) as tar:
            member = tar.next()
            cfg = json.load(tar.extractfile(member))
    except (tarfile.TarError, ValueError, AttributeError):
        return None
    base = default_config()
    for sid, s in cfg.get("services", {}).items():
        base["services"].setdefault(sid, {}).update(s)
    base["custom"] = cfg.get("custom", [])
    return base


def write_config(container: str, cfg: dict) -> None:
    """설정, startup.sh, SSH 공개키를 컨테이너의 /etc/tdock 에 쓴다 (멈춰 있어도 됨)."""
    files = {
        "tdock/services.json": (json.dumps(cfg, indent=1).encode(), 0o644),
        "tdock/startup.sh": (render_script(cfg).encode(), 0o755),
        "tdock/authorized_keys": ((cfg["services"]["ssh"].get("authorized_keys") or "").strip().encode() + b"\n", 0o600),
    }
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w") as tar:
        d = tarfile.TarInfo("tdock")
        d.type, d.mode, d.mtime = tarfile.DIRTYPE, 0o755, int(time.time())
        tar.addfile(d)
        for name, (data, mode) in files.items():
            info = tarfile.TarInfo(name)
            info.size, info.mode, info.mtime = len(data), mode, int(time.time())
            tar.addfile(info, io.BytesIO(data))
    p = _docker("cp", "-", f"{container}:/etc", data=buf.getvalue())
    if p.returncode != 0:
        raise RuntimeError(p.stderr.decode().strip() or "docker cp failed")


def copy_config(src: str, dst: str) -> bool:
    """src 컨테이너의 /etc/tdock 을 dst 로 옮긴다 (commit 없이 다시 만들 때)."""
    p = _docker("cp", f"{src}:{CONF_DIR}", "-")
    if p.returncode != 0:
        return False
    return _docker("cp", "-", f"{dst}:/etc", data=p.stdout).returncode == 0


def exec_script(container: str, *args: str) -> str:
    p = _docker("exec", "-u", "0", container, "sh", SCRIPT, *args)
    if p.returncode != 0:
        raise RuntimeError(p.stderr.decode().strip() or f"startup.sh {' '.join(args)} failed")
    return p.stdout.decode()


def status(container: str) -> dict[str, str]:
    try:
        out = exec_script(container, "status")
    except RuntimeError:
        return {}
    return dict(line.split(None, 1) for line in out.splitlines() if " " in line)


def installed(container: str) -> dict[str, bool]:
    """실행 중인 컨테이너 안에 각 서비스 프로그램이 있는지."""
    checks = {"ssh": "command -v sshd >/dev/null || [ -x /usr/sbin/sshd ]",
              "tunnel": "command -v code >/dev/null",
              "jupyter": "command -v jupyter >/dev/null"}
    script = "; ".join(f'if {c}; then echo "{sid} 1"; else echo "{sid} 0"; fi' for sid, c in checks.items())
    p = _docker("exec", container, "sh", "-c", script)
    if p.returncode != 0:
        return {}
    return {k: v == "1" for k, v in (line.split() for line in p.stdout.decode().splitlines() if " " in line)}


def read_log(container: str, sid: str, lines: int = 300) -> str:
    p = _docker("exec", container, "tail", "-n", str(lines), f"{LOG_DIR}/{sid}.log")
    return p.stdout.decode(errors="replace") if p.returncode == 0 else "(no log yet)"


def plan(old: dict, new: dict) -> tuple[list[str], list[str], list[str]]:
    """바로 반영할 때 (멈출 것, 띄울 것, 실행 중이면 다시 띄울 것). 바뀌지 않은 서비스는 건드리지 않는다."""
    old_ids = set(_ids(old))
    stop = sorted(old_ids - set(_ids(new)))
    start, restart = [], []
    for sid in _ids(new):
        n = service_entry(new, sid)
        o = service_entry(old, sid) if sid in old_ids else None
        was_auto, now_auto = bool(o and o.get("autostart")), bool(n.get("autostart"))
        changed = o is not None and (_body(old, sid) != _body(new, sid) or o.get("keep") != n.get("keep"))
        if was_auto and not now_auto:
            stop.append(sid)
        elif now_auto and not was_auto:
            start.append(sid)
        elif changed:
            restart.append(sid)
    return stop, start, restart


def new_custom_id(cfg: dict) -> str:
    used = {c["id"] for c in cfg.get("custom", [])}
    n = 1
    while f"cmd{n}" in used:
        n += 1
    return f"cmd{n}"


def valid_custom_command(cmd: str) -> str | None:
    if not cmd.strip():
        return "Command is empty."
    if re.search(r"&\s*$", cmd.strip()):
        return "Run the command in the foreground (no trailing &); tdock runs it in the background."
    return None
